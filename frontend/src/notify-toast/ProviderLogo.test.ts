import { describe, expect, it } from "vitest";
import { logoSrc, tileColor } from "./ProviderLogo";

describe("ProviderLogo pure helpers", () => {
  describe("logoSrc", () => {
    it("returns correct svg path for known ids", () => {
      expect(logoSrc("github")).toBe("/activity-logos/github.svg");
      expect(logoSrc("googlecalendar")).toBe("/activity-logos/googlecalendar.svg");
      expect(logoSrc("aider")).toBe("/activity-logos/aider.svg");
      expect(logoSrc("GitHub")).toBe("/activity-logos/github.svg");
      expect(logoSrc("claude")).toBe("/activity-logos/claude.svg");
      expect(logoSrc("gemini")).toBe("/activity-logos/gemini.svg");
    });

    it("returns null for unknown id", () => {
      expect(logoSrc("unknown_app")).toBeNull();
      expect(logoSrc("nonexistent")).toBeNull();
    });

    it("returns null for empty id or whitespace", () => {
      expect(logoSrc("")).toBeNull();
      expect(logoSrc("   ")).toBeNull();
      expect(logoSrc(null)).toBeNull();
      expect(logoSrc(undefined)).toBeNull();
    });

    it("returns null for agent icon (uses monogram fallback)", () => {
      expect(logoSrc("agent")).toBeNull();
      expect(logoSrc("Agent")).toBeNull();
    });
  });

  describe("tileColor", () => {
    it("returns brand color for known ids including new ones", () => {
      expect(tileColor("github")).toBe("#181717");
      expect(tileColor("googlecalendar")).toBe("#4285f4");
      expect(tileColor("aider")).toBe("#f4f4f6");
      expect(tileColor("vercel")).toBe("#000000");
      expect(tileColor("codex")).toBe("#ffffff");
      expect(tileColor("antigravity")).toBe("#ffffff");
      expect(tileColor("copilot")).toBe("#ffffff");
      expect(tileColor("GitHub")).toBe("#181717");
    });

    it("returns undefined for unknown id", () => {
      expect(tileColor("unknown_app")).toBeUndefined();
      expect(tileColor("nonexistent")).toBeUndefined();
    });

    it("returns undefined for empty id or whitespace", () => {
      expect(tileColor("")).toBeUndefined();
      expect(tileColor("   ")).toBeUndefined();
      expect(tileColor(null)).toBeUndefined();
      expect(tileColor(undefined)).toBeUndefined();
    });

    it("returns undefined for agent icon", () => {
      expect(tileColor("agent")).toBeUndefined();
      expect(tileColor("Agent")).toBeUndefined();
    });
  });
});

// Every icon the toast or Hub can show must be visible on the tile it is given: a mark painted in the tile's own
// colour (Claude on its orange, Supabase on its green) is invisible. The tile table is generated by
// scripts/gen-icon-tiles.mjs (CI runs it with --check), which uses the same contrast rule as this test.
import { readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import { tileColor as tileOf } from "./ProviderLogo";

describe("every icon is visible on its tile", () => {
  const dir = resolve(__dirname, "../../public/activity-logos");
  const NAMED: Record<string, string> = { white: "#ffffff", black: "#000000" };
  const full = (h: string) => (h.length === 4 ? "#" + [...h.slice(1)].map((c) => c + c).join("") : h).toLowerCase();
  const lum = (h: string) => {
    const f = (v: number) => { const c = v / 255; return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); };
    return 0.2126 * f(parseInt(h.slice(1, 3), 16)) + 0.7152 * f(parseInt(h.slice(3, 5), 16)) + 0.0722 * f(parseInt(h.slice(5, 7), 16));
  };
  const ratio = (a: string, b: string) => { const [hi, lo] = [lum(a), lum(b)].sort((p, q) => q - p); return (hi + 0.05) / (lo + 0.05); };
  const paints = (svg: string) => {
    const out: string[] = [];
    for (const m of svg.matchAll(/\b(?:fill|stroke)\s*[=:]\s*["']?\s*(#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3}|currentColor|white|black|url\(#[^)]*\))/g)) {
      const v = m[1];
      out.push(v === "currentColor" ? "#000000" : NAMED[v] ?? (v.startsWith("url(") ? "#5a7fe0" : full(v)));
    }
    return out.length ? out : ["#000000"];
  };
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".svg"))) {
    const id = f.slice(0, -4);
    const tile = tileOf(id);
    if (!tile || !/^#[0-9a-f]{6}$/i.test(tile)) continue;
    const p = paints(readFileSync(resolve(dir, f), "utf8"));
    it(`${id} on ${tile}`, () => {
      expect(Math.max(...p.map((c) => ratio(c, tile))), p.slice(0, 3).join(" ")).toBeGreaterThanOrEqual(1.8);
    });
  }
});
